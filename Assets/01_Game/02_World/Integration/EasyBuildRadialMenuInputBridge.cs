        public string GetHudItemLabel(int hudItemIndex)
        {
            if (hudItemIndex < 0) return null;

            if (TryResolveFilteredHudPart(hudItemIndex, out var filteredPart))
            {
                var filteredDisplayName = ResolvePartDisplayName(filteredPart);
                return string.IsNullOrWhiteSpace(filteredDisplayName)
                    ? $"Item {hudItemIndex + 1}"
                    : filteredDisplayName;
            }

            var slotCount = GetBuildItemCount();
            if (hudItemIndex == LegacyHudCancelSlotIndex && slotCount <= LegacyHudCancelSlotIndex)
                return "Cancel [Esc]";

            var part = ResolveHudPart(hudItemIndex);
            var partDisplayName = ResolvePartDisplayName(part);
            if (!string.IsNullOrWhiteSpace(partDisplayName))
                return partDisplayName;

            if (TryResolveRadialSlotVisualData(hudItemIndex, out var slotLabel, out _)
                && !string.IsNullOrWhiteSpace(slotLabel))
            {
                return slotLabel.Trim();
            }

            return $"Item {hudItemIndex + 1}";
        }

        public Texture2D GetHudItemTexture(int hudItemIndex)
        {
            if (hudItemIndex < 0) return null;

            if (TryResolveFilteredHudPart(hudItemIndex, out var filteredPart))
            {
                if (TryResolveSpriteFromLibrary(filteredPart, out _))
                    return null;

                return EasyBuildBridgePartDataHelper.ResolveMainTextureFromPart(filteredPart);
            }

            var slotCount = GetBuildItemCount();
            if (hudItemIndex == LegacyHudCancelSlotIndex && slotCount <= LegacyHudCancelSlotIndex) return null;

            if (TryResolveRadialSlotVisualData(hudItemIndex, out _, out var slotTexture) && slotTexture != null)
                return slotTexture;

            var part = ResolveHudPart(hudItemIndex);
            if (part == null) return null;

            if (TryResolveSpriteFromLibrary(part, out _))
                return null;

            return EasyBuildBridgePartDataHelper.ResolveMainTextureFromPart(part);
        }

        /// <summary>
        ///     Some Easy Build catalog rows store a <see cref="Sprite" /> on the slot/action instead of a standalone <see cref="Texture2D" />.
        ///     Use for Unity UI <see cref="UnityEngine.UI.Image" /> when <see cref="GetHudItemTexture" /> returns null.
        /// </summary>
        public Sprite GetHudItemSprite(int hudItemIndex)
        {
            if (hudItemIndex < 0) return null;

            var slotCount = GetBuildItemCount();
            if (hudItemIndex == LegacyHudCancelSlotIndex && slotCount <= LegacyHudCancelSlotIndex) return null;
            if (hudItemIndex >= slotCount) return null;

            if (TryResolveHudSpriteFromLibrary(hudItemIndex, out var librarySprite))
                return librarySprite;

            if (!TryResolveRadialMenu(out var radialMenu) || radialMenu == null) return null;

            return EasyBuildBridgeHudVisualHelper.ResolveSpriteFromRadialMenu(radialMenu, hudItemIndex);
        }


        public bool TryCancelBuildUi()
        {
            ForceCloseBuildUi();
            BridgeLog("Build UI cancel requested");
            return true;
        }

        public bool TryActivateHudItem(int hudItemIndex)
        {
            if (hudItemIndex < 0) return false;

            if (TrySelectFilteredPartByHudIndex(hudItemIndex))
            {
                _currentHudSelectionIndex = hudItemIndex;
                SetPlacementMode();
                _manualBuildModeActive = true;
                BridgeLog($"HUD item activated (filtered): index={hudItemIndex}");
                return true;
            }

            var slotCount = GetBuildItemCount();

            // Legacy: index 9 meant "cancel" only when the category had at most 9 slot indices (0..8).
            if (hudItemIndex == LegacyHudCancelSlotIndex && slotCount <= LegacyHudCancelSlotIndex)
                return TryCancelBuildUi();

            if (slotCount <= 0 || hudItemIndex >= slotCount)
            {
                BridgeLog($"Activate HUD item failed: index={hudItemIndex}, slotCount={slotCount}");
                return false;
            }

            if (!TrySelectPartByHudIndex(hudItemIndex))
            {
                BridgeLog($"Activate HUD item failed selecting part: index={hudItemIndex}");
                return false;
            }

            _currentHudSelectionIndex = hudItemIndex;
            SetPlacementMode();
            _manualBuildModeActive = true;
            BridgeLog($"HUD item activated: index={hudItemIndex}");
            return true;
        }


