        /// <summary>
        ///     Legacy HUD reserved index 9 for "cancel" only when the active category had ≤9 part slots
        ///     (indices 0..8). Larger catalogs use index 9 as a real part — use <see cref="TryCancelBuildUi" /> for cancel.
        /// </summary>
        public const int LegacyHudCancelSlotIndex = 9;

        public int GetBuildCategoryCount()
        {
            if (IsUsingExtensionFolderFilter())
                return GetFilteredCatalogPartCount() > 0 ? 1 : 0;

            if (!TryResolveRadialMenu(out var radialMenu) || radialMenu == null)
            {
                return GetBuildItemCountFromManager() > 0 ? 1 : 0;
            }

            return EasyBuildBridgeRadialMenuStateHelper.GetBuildCategoryCount(radialMenu);
        }

        public int GetActiveBuildCategoryIndex()
        {
            if (IsUsingExtensionFolderFilter())
                return GetFilteredCatalogPartCount() > 0 ? 0 : -1;

            if (!TryResolveRadialMenu(out var radialMenu) || radialMenu == null) return -1;

            return EasyBuildBridgeRadialMenuStateHelper.GetActiveBuildCategoryIndex(
                radialMenu,
                ResolveActiveOrFirstCategory);
        }

        public bool TrySetActiveBuildCategory(int categoryIndex)
        {
            if (IsUsingExtensionFolderFilter())
                return categoryIndex == 0 && GetFilteredCatalogPartCount() > 0;

            if (categoryIndex < 0) return false;
            if (!TryResolveRadialMenu(out var radialMenu) || radialMenu == null)
            {
                BridgeLog($"Set category failed: radial menu unavailable (requested={categoryIndex})");
                return false;
            }

            if (!EasyBuildBridgeRadialMenuStateHelper.TrySetActiveBuildCategory(
                    radialMenu,
                    categoryIndex,
                    ResolveRadialCategoryByIndex))
            {
                BridgeLog($"Set category failed: category index not found ({categoryIndex})");
                return false;
            }

            BridgeLog($"Active category set to {categoryIndex}");
            return true;
        }

        public int GetBuildItemCount()
        {
            if (IsUsingExtensionFolderFilter())
                return GetFilteredCatalogPartCount();

            if (!TryResolveRadialMenu(out var radialMenu) || radialMenu == null)
            {
                BridgeLog("GetBuildItemCount using manager fallback: radial menu unavailable", true);
                return GetBuildItemCountFromManager();
            }

            if (!EasyBuildBridgeRadialMenuStateHelper.TryGetBuildItemCountFromActiveCategory(
                    radialMenu,
                    ResolveActiveOrFirstCategory,
                    out var count))
                return 0;

            if (count > 0) return count;

            BridgeLog("GetBuildItemCount using manager fallback: active category has zero slots", true);
            return GetBuildItemCountFromManager();
        }


        public string GetBuildControlsHelpText()
